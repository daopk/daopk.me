import { mkdir, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const { getIconData } = require("@iconify/utils");
const fluentColorCollection = require("@iconify-json/fluent-color/icons.json");

const ICON_NAMES = [
  "apps-24",
  "apps-32",
  "apps-list-24",
  "apps-list-detail-24",
  "arrow-sync-24",
  "calendar-32",
  "clock-32",
  "cloud-24",
  "code-block-32",
  "document-24",
  "document-32",
  "document-folder-24",
  "document-text-24",
  "edit-32",
  "globe-24",
  "image-24",
  "laptop-24",
  "notebook-32",
  "paint-brush-24",
  "person-starburst-32",
  "settings-32",
  "shield-24",
  "text-edit-style-24",
];

const outputPath = fileURLToPath(new URL("../src/icons/generated/fluentColor.ts", import.meta.url));

function assertUnique(names) {
  const seen = new Set();
  const duplicates = names.filter((name) => {
    if (seen.has(name)) {
      return true;
    }
    seen.add(name);
    return false;
  });

  if (duplicates.length > 0) {
    throw new Error(`Duplicate Fluent Color icon names: ${duplicates.join(", ")}`);
  }
}

function iconDataFor(name) {
  const icon = getIconData(fluentColorCollection, name);
  if (!icon) {
    throw new Error(`Missing Fluent Color icon: ${name}`);
  }
  return icon;
}

function stringLiteral(value) {
  return `'${value.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;
}

function namesLiteral() {
  return `[
${ICON_NAMES.map((name) => `  ${JSON.stringify(name)},`).join("\n")}
]`;
}

function iconLiteral(icon) {
  return `{
    width: ${icon.width},
    height: ${icon.height},
    body: ${stringLiteral(icon.body)},
  }`;
}

function iconDataLiteral(iconData) {
  const entries = ICON_NAMES.map((name) => `  "${name}": ${iconLiteral(iconData[name])},`).join(
    "\n",
  );

  return `{
${entries}
}`;
}

function generatedSource(iconData) {
  return `// Generated by scripts/generate-fluent-color-icons.mjs.
// Do not edit manually.

import type { IconifyIcon } from "@iconify/utils";

export const fluentColorIconNames = ${namesLiteral()} as const;

export type FluentColorIconName = (typeof fluentColorIconNames)[number];

export const fluentColorIconData = ${iconDataLiteral(iconData)} as const satisfies Record<FluentColorIconName, IconifyIcon>;
`;
}

assertUnique(ICON_NAMES);

const iconData = Object.fromEntries(ICON_NAMES.map((name) => [name, iconDataFor(name)]));

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, generatedSource(iconData));

console.log(`Generated ${ICON_NAMES.length} Fluent Color icons at ${outputPath}`);
